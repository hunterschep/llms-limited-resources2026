#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

from lineage_common import EDIT_REPAIR_TINY, ORIGINAL_STAGE_B, STAGE_B_MERGED, aggregate_row, markdown_table, write_json  # noqa: E402


DEFAULT_CANDIDATES = {
    "prompt_only": "Qwen/Qwen3.5-2B",
    "original_stage_b": ORIGINAL_STAGE_B,
    "edit_repair_tiny": EDIT_REPAIR_TINY,
    "reproduced_stage_b": STAGE_B_MERGED,
}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", default="configs/eval/sorbian.yaml")
    parser.add_argument("--candidate", nargs=2, action="append", metavar=("NAME", "MODEL"))
    parser.add_argument("--output-dir", default="results/lineage_recovery/full_eval")
    parser.add_argument("--run", action="store_true")
    args = parser.parse_args()
    out_dir = ROOT / args.output_dir
    out_dir.mkdir(parents=True, exist_ok=True)
    candidates = dict(DEFAULT_CANDIDATES)
    for item in args.candidate or []:
        candidates[item[0]] = item[1]
    rows = []
    for name, model in candidates.items():
        output = out_dir / f"{name}.json"
        if args.run:
            if name != "prompt_only" and not Path(model).exists():
                print(f"lineage_full_eval_skip missing name={name} model={model}", flush=True)
                rows.append({"model": name, "exists": False, "decision": "missing"})
                continue
            subprocess.run(
                [sys.executable, "scripts/competitive_eval.py", "--config", args.config, "--model", model, "--output", str(output.relative_to(ROOT)), "--raw-output", str((out_dir / f"{name}_raw.jsonl").relative_to(ROOT))],
                cwd=ROOT,
                check=True,
            )
        rows.append(aggregate_row(name, output))
    write_json(out_dir / "full_eval_summary.json", {"candidates": rows})
    doc = ROOT / "docs/100_lineage_recovery_results.md"
    doc.parent.mkdir(parents=True, exist_ok=True)
    doc.write_text(
        "\n".join(
            [
                "# Lineage Recovery Results",
                "",
                "This table is regenerated by `scripts/lineage_full_eval_candidates.py`.",
                "",
                markdown_table(rows, ["model", "overall", "MT", "QA", "SC", "GC", "MR", "decision"]),
                "",
            ]
        ),
        encoding="utf-8",
    )
    print(json.dumps(rows, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
